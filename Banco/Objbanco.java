public class Objbanco {
    int Ident;
    String Nombre;
    String Tipo_de_trámite;
    int Edad;
    int Condición_especial;
    int Número_turno;

    public Objbanco() {
    }

    public int getIdent() {
        return Ident;
    }

    public void setIdent(int ident) {
        Ident = ident;
    }

    public String getNombre() {
        return Nombre;
    }

    public void setNombre(String nombre) {
        Nombre = nombre;
    }

    public String getTipo_de_trámite() {
        return Tipo_de_trámite;
    }

    public void setTipo_de_trámite(String tipo_de_trámite) {
        Tipo_de_trámite = tipo_de_trámite;
    }

    public int getEdad() {
        return Edad;
    }

    public void setEdad(int edad) {
        Edad = edad;
    }

    public int getCondición_especial() {
        return Condición_especial;
    }

    public void setCondición_especial(int condición_especial) {
        Condición_especial = condición_especial;
    }

    public int getNúmero_turno() {
        return Número_turno;
    }

    public void setNúmero_turno(int número_turno) {
        Número_turno = número_turno;
    }

}